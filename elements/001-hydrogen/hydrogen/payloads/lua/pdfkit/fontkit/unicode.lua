--------------------------------------------------------------------------------
-- Lookup
--------------------------------------------------------------------------------

--- The value whose run contains `cp`.
---
--- The runs tile the code space from 0 upwards, so this is a search for the
--- last start that is not past the code point. Anything at or above the last
--- boundary lands in the final run, which is what a code point beyond
--- U+10FFFF should get: the unassigned answer.
local function lookup(starts, values, cp)
    local lo, hi = 1, #starts

    while lo < hi do
        local mid = (lo + hi + 1) // 2
        if starts[mid] <= cp then
            lo = mid
        else
            hi = mid - 1
        end
    end

    return values[lo]
end

local M = {}

--- True for a combining mark -- general category Mn, Me or Mc.
function M.is_mark(cp)
    return lookup(MARK_starts, MARK_values, cp)
end

--- True for a decimal digit -- general category Nd.
function M.is_digit(cp)
    return lookup(DIGIT_starts, DIGIT_values, cp)
end

--- The canonical combining class, by name. 'Not_Reordered' for class zero,
--- which is most of Unicode.
function M.get_combining_class(cp)
    return lookup(COMBINING_starts, COMBINING_values, cp)
end

--- The script name. 'Common' for punctuation and digits, 'Unknown' for
--- unassigned code points -- both of which the script detector skips over.
function M.get_script(cp)
    return lookup(SCRIPT_starts, SCRIPT_values, cp)
end

return M
