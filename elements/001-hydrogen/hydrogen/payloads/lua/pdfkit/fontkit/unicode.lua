-- fontkit/unicode.lua -- stand-in for the `unicode-properties` package
--
-- Four character properties fontkit reads out of the Unicode database:
--
--   is_mark             -- general category Mn, Me or Mc. Decides whether a
--                          glyph is a combining mark, which drives both the
--                          fallback mark positioning and GPOS attachment.
--   is_digit            -- general category Nd. Read by the default shaper.
--   get_combining_class -- the canonical combining class, as a *name*
--                          ('Above', 'Below', 'CCC24', ...). Positions marks
--                          around their base when the font has no GPOS.
--   get_script          -- the script a character belongs to, as an ISO 15924
--                          long name ('Latin', 'Arabic', ...). Picks the
--                          shaper and the default text direction.
--
-- The data below is generated, not transcribed: a script walked all 1,114,112
-- code points through the same package fontkit imports and recorded where the
-- answer changed. Each property is two parallel arrays -- the code point each
-- run starts at, and the value for that run -- covering the space with no
-- gaps, so a lookup is one binary search and never a miss.
--
-- Storing runs rather than a trie costs a few hundred nanoseconds per lookup
-- and saves carrying a compressed trie decoder. Scripts are the largest at
-- 1,369 runs; marks collapse to 561.
--
-- The upstream package exposes more than this -- categories, numeric values,
-- east asian width. Nothing in fontkit reads them, so they are not here.

