-- fontkit/encodings.lua -- port of fontkit/src/encodings.js
--
-- Every string in a font's `name` table is tagged with a platform id, an
-- encoding id and a language id. The first two pick a character encoding and the
-- third picks a language tag to file the result under. The three tables below are
-- those maps, transcribed from the fontkit source.
--
-- The data here was generated from fontkit/src/encodings.js rather than typed by
-- hand, so the tables are byte-for-byte what fontkit has, including the entries
-- that look like typos and the two languages that share a code.
--
-- Indexing is zero-based, matching the ids as they appear in the font, so
-- ENCODINGS[3][1] is platform 3 encoding 1 with no arithmetic in between.
--
-- On decoding. restructure hands each name string to TextDecoder and, when
-- TextDecoder does not know the encoding, gives back the raw bytes instead of a
-- string -- which fontkit then detects with a `typeof === 'string'` test and
-- treats as lower priority than a real string. That two-tier behaviour is
-- reproduced here: decode() returns the decoded text and true, or the original
-- bytes and false.
--
-- The encodings that decode are utf-16be and the seven single-byte ones whose
-- high halves are tabulated below. The five multi-byte CJK encodings (shift-jis,
-- big5, euc-kr, gbk, gb18030) come back as bytes, where TextDecoder would have
-- produced text -- the only deliberate divergence in this file, and the tables to
-- close it run to tens of thousands of entries. It costs nothing downstream:
-- pdfkit reads exactly one name, postscriptName, which the spec requires to be
-- ASCII, and a CJK record files itself under a CJK language tag regardless.

