--- Pick an encoding name from a name record's three ids.
---
--- The mac language override is checked first, exactly as upstream does, so a
--- platform-1 record in Turkish comes back as x-mac-turkish rather than
--- x-mac-roman. Returns nil for the combinations that have no entry at all.
function M.get_encoding(platformID, encodingID, languageID)
    languageID = languageID or 0

    if platformID == 1 and MAC_LANGUAGE_ENCODINGS[languageID] then
        return MAC_LANGUAGE_ENCODINGS[languageID]
    end

    local row = ENCODINGS[platformID]
    return row and row[encodingID]
end

--- The only encodings a cmap can be inverted through, and the cache of the
