--- in SINGLE_BYTE, from TextDecoder, and in INVERTIBLE.) Only the high half is
--- built: bytes below 0x80 are ASCII and are handled by the caller.
---
--- Duplicates resolve the way an insertion into a Map does -- the last byte to
--- claim a code point wins. That is not academic: iso-8859-6 and iso-8859-8
--- leave most of their high half undefined and TextDecoder gives every one of
--- those bytes U+FFFD, so U+FFFD ends up meaning whichever undefined byte comes
--- last. Reproduced, since a lookup of U+FFFD is meaningless either way.
---
--- Returns nil for an encoding that cannot be inverted, which is the signal
--- CmapProcessor uses to skip a subtable.
function M.get_encoding_mapping(encoding)
    local cached = mapping_cache[encoding]
    if cached then
        return cached
    end

    -- Not supported by TextDecoder, so upstream carries the table itself.
    local high = MAC_ENCODINGS[encoding]

    -- Only single byte encodings can be mapped 1:1.
    if not high and INVERTIBLE[encoding] then
        high = SINGLE_BYTE[encoding]
    end

    if not high then
        return nil
    end

    local res = {}
    for i = 1, 128 do
        res[high[i]] = 0x7F + i
    end

    mapping_cache[encoding] = res
    return res
end

--- Decode a name string. Returns the text and true, or the raw bytes and false.
---
--- The second return value is the `typeof s === 'string'` test upstream makes on
--- the result: a record that failed to decode still gets stored, but a record
--- that decoded will displace it. See the note at the top of the file for which
--- encodings land on which side.
function M.decode(s, encoding)
    if encoding == "utf-16be" then
        return reader.decode_utf16be(s), true
    end

    local high = SINGLE_BYTE[encoding]
    if high then
        return reader.decode_single_byte(s, high), true
    end

    return s, false
end

return M
